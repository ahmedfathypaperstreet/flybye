#!/usr/bin/env bash
# ============================================================================
# FlyBye — bootstrap script
# ============================================================================
# Takes the repo from "code only" to "runnable on iPhone" in one go:
#   1. flutter create  (generates ios/ + android/ without touching lib/)
#   2. flutter pub get
#   3. Copies generated app icons into the new ios/ and android/ paths
#   4. Patches Info.plist with our permission strings + URL scheme
#   5. Patches AndroidManifest.xml with our intent-filter + permissions
#   6. cd ios && pod install
#
# Idempotent: re-running skips work that's already done.
#
# Run from the FlyBye App directory:
#   bash scripts/bootstrap.sh
# ============================================================================

set -euo pipefail

# --- locate repo ------------------------------------------------------------
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
echo "→ working in $ROOT"
echo

# --- preflight --------------------------------------------------------------
need() { command -v "$1" >/dev/null 2>&1 || { echo "✗ missing: $1" >&2; exit 1; }; }
need flutter
need python3
need /usr/libexec/PlistBuddy

if [ ! -d "lib" ]; then
  echo "✗ lib/ missing. Are you in the FlyBye App folder?" >&2
  exit 1
fi

flutter --version 2>/dev/null || true

# --- 1. flutter create ------------------------------------------------------
# Detect whether the platform folders were ACTUALLY generated by checking for
# files only flutter create produces (not just our icon copies).
if [ ! -f "ios/Runner/Info.plist" ] || [ ! -f "android/app/src/main/AndroidManifest.xml" ]; then
  echo
  echo "→ flutter create (generating ios/ + android/)"
  flutter create \
    --platforms=ios,android \
    --org app.flybye \
    --project-name flybye \
    .
else
  echo "✓ flutter project already initialized (skipping flutter create)"
fi

# --- 2. flutter pub get -----------------------------------------------------
echo
echo "→ flutter pub get"
flutter pub get

# --- 3. Copy iOS app icons --------------------------------------------------
echo
echo "→ copying iOS app icons"
IOS_ICON_DST="ios/Runner/Assets.xcassets/AppIcon.appiconset"
if [ -d "assets/icons/ios/AppIcon.appiconset" ]; then
  rm -rf "$IOS_ICON_DST"
  cp -R "assets/icons/ios/AppIcon.appiconset" "$(dirname "$IOS_ICON_DST")/"
  echo "  ✓ $IOS_ICON_DST replaced"
else
  echo "  ! assets/icons/ios/AppIcon.appiconset not found (run icon generator)"
fi

# --- 4. Copy Android icons --------------------------------------------------
echo
echo "→ copying Android launcher icons"
for d in mdpi hdpi xhdpi xxhdpi xxxhdpi; do
  src="assets/icons/android/mipmap-$d/ic_launcher.png"
  dst="android/app/src/main/res/mipmap-$d/ic_launcher.png"
  if [ -f "$src" ]; then
    mkdir -p "$(dirname "$dst")"
    cp "$src" "$dst"
    echo "  ✓ mipmap-$d"
  fi
done

# Adaptive icon (Android 8+)
mkdir -p android/app/src/main/res/mipmap-anydpi-v26
cp -f assets/icons/android/mipmap-anydpi-v26/ic_launcher.xml \
      android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml
cp -f assets/icons/android/ic_launcher_foreground.png \
      android/app/src/main/res/mipmap-xxxhdpi/ic_launcher_foreground.png
cp -f assets/icons/android/ic_launcher_background.png \
      android/app/src/main/res/mipmap-xxxhdpi/ic_launcher_background.png
echo "  ✓ adaptive icon"

# --- 5. Patch Info.plist with PlistBuddy ------------------------------------
echo
echo "→ patching ios/Runner/Info.plist"
PLIST="ios/Runner/Info.plist"

set_str() { /usr/libexec/PlistBuddy -c "Delete :$1" "$PLIST" 2>/dev/null || true
            /usr/libexec/PlistBuddy -c "Add :$1 string $2" "$PLIST"; }
set_bool() { /usr/libexec/PlistBuddy -c "Delete :$1" "$PLIST" 2>/dev/null || true
             /usr/libexec/PlistBuddy -c "Add :$1 bool $2" "$PLIST"; }

set_str NSCameraUsageDescription \
  "FlyBye needs your camera to take a verification selfie when you sign up."
set_str NSPhotoLibraryUsageDescription \
  "FlyBye uses your photos so you can pick a profile picture."
set_str NSPhotoLibraryAddUsageDescription \
  "FlyBye saves photos you share in chat."
set_str NSMicrophoneUsageDescription \
  "FlyBye does not record audio. Reserved for future voice messages."
set_bool ITSAppUsesNonExemptEncryption false

# CFBundleURLTypes (deep link). Adding only if not present.
if ! /usr/libexec/PlistBuddy -c "Print :CFBundleURLTypes" "$PLIST" >/dev/null 2>&1; then
  /usr/libexec/PlistBuddy -c "Add :CFBundleURLTypes array" "$PLIST"
  /usr/libexec/PlistBuddy -c "Add :CFBundleURLTypes:0 dict" "$PLIST"
  /usr/libexec/PlistBuddy -c "Add :CFBundleURLTypes:0:CFBundleTypeRole string Editor" "$PLIST"
  /usr/libexec/PlistBuddy -c "Add :CFBundleURLTypes:0:CFBundleURLSchemes array" "$PLIST"
  /usr/libexec/PlistBuddy -c "Add :CFBundleURLTypes:0:CFBundleURLSchemes:0 string flybye" "$PLIST"
  echo "  ✓ added flybye:// URL scheme"
else
  echo "  ✓ CFBundleURLTypes already present (skipping)"
fi

# --- 6. Patch AndroidManifest.xml -------------------------------------------
echo
echo "→ patching android/app/src/main/AndroidManifest.xml"
python3 - "$ROOT" <<'PY'
import sys, re
from pathlib import Path
root = Path(sys.argv[1])
manifest = root / 'android/app/src/main/AndroidManifest.xml'
src = manifest.read_text()

# Add uses-permission lines after <manifest ... >
perms = '''    <uses-permission android:name="android.permission.INTERNET" />
    <uses-permission android:name="android.permission.CAMERA" />
    <uses-permission android:name="android.permission.READ_MEDIA_IMAGES" />
    <uses-permission android:name="android.permission.READ_EXTERNAL_STORAGE" android:maxSdkVersion="32" />
'''

if 'android.permission.CAMERA' not in src:
    src = re.sub(
        r'(<manifest[^>]*>\s*)',
        r'\1\n' + perms,
        src, count=1)
    print('  + permissions inserted')
else:
    print('  · permissions already present')

# Add deep-link intent-filter inside the main activity, after the existing
# intent-filter that has android.intent.action.MAIN.
deep_link = '''            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="flybye" android:host="reset-password" />
            </intent-filter>
'''

if 'android:scheme="flybye"' not in src:
    # Find the </intent-filter> that closes the MAIN/LAUNCHER intent-filter
    pattern = re.compile(
        r'(<intent-filter>\s*<action android:name="android\.intent\.action\.MAIN"[^/]*/>\s*'
        r'<category android:name="android\.intent\.category\.LAUNCHER"\s*/>\s*</intent-filter>)',
        re.S)
    src, n = pattern.subn(r'\1\n' + deep_link, src, count=1)
    if n:
        print('  + deep-link intent-filter inserted')
    else:
        print('  ! could not locate MAIN intent-filter — paste manually')
else:
    print('  · deep link already present')

manifest.write_text(src)
PY

# --- 7. CocoaPods -----------------------------------------------------------
if [ -d ios ]; then
  echo
  echo "→ pod install"
  (cd ios && pod install)
fi

# --- 8. Done ----------------------------------------------------------------
echo
echo "──────────────────────────────────────────────────────────────"
echo "✓ Bootstrap complete."
echo
echo "Next:"
echo "  1. Open ios/Runner.xcworkspace in Xcode"
echo "  2. Select Runner → Signing & Capabilities → set your Team"
echo "  3. Plug in your iPhone, accept the trust prompt"
echo "  4. flutter run --release -d <your iPhone name>"
echo "──────────────────────────────────────────────────────────────"
